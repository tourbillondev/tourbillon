import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/// The website's contract interface, taken from the Foundry build (never written by hand): the functions and events the
/// live adapter calls, and every custom error those contracts can revert with, so a refusal reaches the user by name.
///   bun scripts/abi.ts            writes src/live/abi.generated.mjs
///   bun scripts/abi.ts --check    exits 1 when the file differs from the build (the drift test runs this)

const OUT = resolve(import.meta.dir, "../../contracts/out");
const TARGET = resolve(import.meta.dir, "../src/live/abi.generated.mjs");

/// contract → the functions and events the adapter uses
export const WANT: Record<string, { functions: string[]; events: string[] }> = {
  OpenBook: { functions: ["buy"], events: ["Routed"] },
  Engine: { functions: ["sell", "markets", "buysPaused"], events: ["Bought", "ShapeBought", "Sold"] },
  WriterBook: { functions: ["write", "writes"], events: ["Written"] },
  PathFundingBook: { functions: ["balanceOf", "normNow", "isShape"], events: [] },
  MainspringPool: { functions: ["marketPaused", "opensPaused"], events: [] },
  MarkRouter: { functions: ["markWad"], events: [] },
};
/// contracts whose errors can surface through those calls
const ERRORS_FROM = ["OpenBook", "Engine", "WriterBook", "PathFundingBook", "MainspringPool", "MarkRouter", "QuorumBoard", "MatchBook", "VolQuote", "SettlementAdapter", "CoveringAssets"];

type Item = { type: string; name?: string; inputs?: { type: string; components?: unknown[] }[] };
const artifact = (c: string): Item[] => JSON.parse(readFileSync(join(OUT, `${c}.sol`, `${c}.json`), "utf8")).abi;
const sig = (i: Item): string => `${i.name}(${(i.inputs ?? []).map((x) => (x.components ? `(${sig({ name: "", inputs: x.components as Item["inputs"] }).slice(1, -1)})${x.type.slice(5)}` : x.type)).join(",")})`;

export function build(): string {
  const out: Record<string, Item[]> = {};
  for (const [c, w] of Object.entries(WANT)) {
    const abi = artifact(c);
    const pick = (type: string, names: string[]) =>
      names.map((n) => {
        const found = abi.filter((i) => i.type === type && i.name === n);
        if (found.length !== 1) throw new Error(`${c}.${n}: ${found.length} ${type} entries in the build`);
        return found[0]!;
      });
    out[c] = [...pick("function", w.functions), ...pick("event", w.events)];
  }
  const seen = new Map<string, Item>();
  for (const c of ERRORS_FROM) for (const i of artifact(c)) if (i.type === "error" && !seen.has(sig(i))) seen.set(sig(i), i);
  const errors = [...seen.values()].sort((a, b) => sig(a).localeCompare(sig(b)));
  const erc20 = [
    "function balanceOf(address) view returns (uint256)",
    "function allowance(address, address) view returns (uint256)",
    "function approve(address, uint256) returns (bool)",
    "function decimals() view returns (uint8)",
    "function symbol() view returns (string)",
  ];
  return `// Generated by scripts/abi.ts from the Foundry build. Do not edit by hand; run \`bun scripts/abi.ts\`.\n` +
    `export const ERC20 = ${JSON.stringify(erc20, null, 1)};\n` +
    Object.entries(out).map(([c, items]) => `export const ${c} = ${JSON.stringify(items)};\n`).join("") +
    `export const ERRORS = ${JSON.stringify(errors)};\n`;
}

if (import.meta.main) {
  const text = build();
  if (process.argv.includes("--check")) {
    const now = readFileSync(TARGET, "utf8");
    if (now !== text) {
      console.error("src/live/abi.generated.mjs differs from the contracts' build: run bun scripts/abi.ts");
      process.exit(1);
    }
    console.log("abi.generated.mjs matches the build");
  } else {
    writeFileSync(TARGET, text);
    console.log(`wrote ${TARGET}`);
  }
}
